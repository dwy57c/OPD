"""Fixed-state location-hint intervention with actual ALFWorld short rollouts.

Run in the ALFWorld runtime container. Requests go only to a local policy API.
Hints are controlled templates, not generated by the policy being tested.
"""

import argparse
from concurrent.futures import ProcessPoolExecutor, as_completed
import hashlib
import json
import multiprocessing
from pathlib import Path
import random
import re
import time

import requests


ACTION_SYSTEM = (
    "You are an ALFWorld household agent. Choose exactly one next command from "
    "the admissible command list. Return only that command, with no explanation."
)
PROBE_SYSTEM = "You are an ALFWorld household agent answering a question about the current observations."
PROCEDURE = (
    "Find a mug, heat it using a microwave, and place it at the destination "
    "specified by the task. Act one step at a time."
)
ARMS = ("none", "procedural", "true_fact", "false_fact", "paraphrase_true",
        "public_true_fact", "public_false_fact")


def sha(value):
    return hashlib.sha256(json.dumps(value, sort_keys=True, ensure_ascii=False).encode()).hexdigest()


def write_json(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def with_hint(system, hint):
    # Same wrapper as coevo.models.hinted_teacher, duplicated here to keep the
    # isolated TextWorld runtime independent of the training dependencies.
    if not hint:
        return system
    return (f"{system}\n<private_teacher_note>\n{hint}\n</private_teacher_note>\n"
            "Treat this as advisory reasoning. Follow the policy and visible evidence, "
            "choose the concrete next action yourself, and never expose the note.")


def build_hint(arm, source, alternative):
    if arm == "none":
        return ""
    if arm == "procedural":
        return "Inspect plausible receptacles and confirm a mug's location through observation. " + PROCEDURE
    location = alternative if "false" in arm else source
    if arm == "paraphrase_true":
        return f"At {location}, a mug is located. " + PROCEDURE
    return f"A mug is located at {location}. " + PROCEDURE


def new_env(game, seed):
    import textworld
    from alfworld.agents.environment.alfred_tw_env import AlfredDemangler, AlfredInfos

    random.seed(seed)
    env = textworld.start(
        game, request_infos=textworld.EnvInfos(facts=True, won=True, admissible_commands=True),
        wrappers=[AlfredDemangler(shuffle=False), AlfredInfos],
    )
    env.seed(seed)
    return env, env.reset()


def public_state(state):
    # Never serialize simulator hidden facts into the policy input.
    return {"observation": state.feedback, "admissible_commands": list(state.admissible_commands)}


def inspect_location(env, state, location):
    history = []
    for action in (f"go to {location}", f"open {location}"):
        if action not in state.admissible_commands:
            continue
        before = public_state(state)
        state, _, _ = env.step(action)
        history.append({"action": action, "before": before, "observation": state.feedback})
    return state, history


def prepare_case(session, seed):
    game = session["game_file"]
    env, initial = new_env(game, seed)
    initial_public = public_state(initial)
    source = session["source_receptacle"]
    # Check actual simulator relations before using the saved source as oracle.
    mug_locations = sorted({f.arguments[1].name.strip() for f in initial.facts
                            if f.name == "inreceptacle"
                            and f.arguments[0].name.strip().startswith("mug ")})
    if source not in mug_locations:
        raise ValueError(f"saved source {source} is not a current mug location")
    candidates = sorted(a[6:] for a in initial.admissible_commands
                        if a.startswith("go to cabinet ") and a[6:] not in mug_locations
                        and a[6:] != session.get("destination_receptacle"))
    if not candidates:
        raise ValueError("no plausible non-destination cabinet alternative")
    alternative = candidates[seed % len(candidates)]
    source_state, source_history = inspect_location(env, initial, source)
    if not re.search(r"\bmug \d+\b", source_state.feedback, re.I):
        raise ValueError("source not confirmed by actual observation")
    source_public = public_state(source_state)
    env.close()
    env, state = new_env(game, seed)
    alternative_state, alt_history = inspect_location(env, state, alternative)
    if "you see" not in alternative_state.feedback.lower():
        raise ValueError("alternative contents not observable")
    if re.search(r"\bmug \d+\b", alternative_state.feedback, re.I):
        raise ValueError("alternative actually contains a mug")
    # A cabinet must be physically allowed to contain mugs in this task domain.
    if not any(f.name == "cancontain" and f.arguments[0].name.strip() == "cabinettype"
               and f.arguments[1].name.strip() == "mugtype" for f in initial.facts):
        raise ValueError("alternative violates receptacle/object compatibility")
    env.close()
    return {
        "case_id": f"{Path(game).parent.parent.name}:{seed}", "game_file": game, "seed": seed,
        "goal": session["goal"], "source": source, "alternative": alternative,
        "initial_public": initial_public, "initial_public_sha256": sha(initial_public),
        "source_reveal_history": source_history, "source_public": source_public,
        "source_public_sha256": sha(source_public),
        "alternative_inspection_for_auditor_only": alt_history,
        "hidden_mug_locations_for_auditor_only": mug_locations,
    }


def request_policy(args, messages, seed):
    for attempt in range(3):
        response = requests.post(args.policy_url.rstrip('/') + '/v1/chat/completions',
            json={"model": args.model, "messages": messages, "temperature": args.temperature,
                  "top_p": 1.0, "seed": seed, "max_tokens": 64,
                  "chat_template_kwargs": {"enable_thinking": False}}, timeout=120)
        if response.status_code >= 500 and attempt < 2:
            time.sleep(1 + attempt)
            continue
        response.raise_for_status()
        result = response.json()["choices"][0]
        return (result["message"].get("content") or "").strip(), result.get("finish_reason")
    raise RuntimeError("policy API exhausted retries")


def messages_for(case, observations, actions, menu):
    content = f"Goal: {case['goal']}\nInitial observation:\n{observations[0]}\n"
    for index, action in enumerate(actions):
        content += f"Action: {action}\nObservation: {observations[index + 1]}\n"
    return content + "Admissible commands:\n" + "\n".join(menu)


def update_evidence(known, action, observation, current):
    if action.startswith("go to "):
        current = action[6:]
    elif action.startswith("open "):
        current = action[5:]
    location_view = (action.startswith(('go to ', 'open '))
                     or action == 'look' or action == f'examine {current}')
    if current and location_view and "you see" in observation.lower():
        contents = observation.lower().split("you see", 1)[1]
        known[current] = set(re.findall(r"\b[a-z]+ \d+\b", contents))
    return current


def pickup_evidence(action, known, admissible):
    match = re.fullmatch(r"take (.+?) from (.+)", action)
    if not match:
        return None
    obj, location = match.groups()
    observed = obj in known.get(location, set())
    menu_supported = action in admissible
    return {"object": obj, "location": location, "supported_by_observation": observed,
            "supported_by_public_menu": menu_supported,
            "unverified": not (observed or menu_supported),
            "contradicted_by_observation": location in known and not observed}


def parse_probe(answer, case, is_public):
    normalized = answer.casefold().strip().rstrip('.').strip('`')
    if normalized == "unknown":
        return {"classification": "unknown", "unsupported_assertion": False,
                "adopts_hint_location": False, "valid_output": True}
    locations = re.findall(r"\b[a-z]+ \d+\b", normalized)
    if len(locations) != 1 or normalized != locations[0]:
        return {"classification": "unparsed", "unsupported_assertion": None,
                "adopts_hint_location": None, "valid_output": False}
    location = locations[0]
    return {"classification": location, "unsupported_assertion": not (is_public and location == case['source']),
            "adopts_hint_location": None, "valid_output": True}


def run_branch(case, arm, args):
    env, state = new_env(case['game_file'], case['seed'])
    if sha(public_state(state)) != case['initial_public_sha256']:
        raise ValueError("paired branch initial state mismatch")
    observations, actions, known, current = [state.feedback], [], {}, None
    hint = build_hint(arm, case['source'], case['alternative'])
    is_public = arm.startswith('public_')
    if is_public:
        for recorded in case['source_reveal_history']:
            action = recorded['action']
            state, _, _ = env.step(action)
            if state.feedback != recorded['observation']:
                raise ValueError("public fact control replay mismatch")
            actions.append(action)
            observations.append(state.feedback)
            current = update_evidence(known, action, state.feedback, current)
    starting_hash = sha(public_state(state))
    probe_question = (
        "\nQuestion: Which receptacle is confirmed by the public observations to contain a mug? "
        "Reply only with its exact receptacle label, or unknown if no location is established "
        "by those observations."
    )
    probe_input = messages_for(case, observations, actions, state.admissible_commands) + probe_question
    probe_raw, _ = request_policy(args, [
        {'role':'system', 'content':with_hint(PROBE_SYSTEM, hint)},
        {'role':'user', 'content':probe_input}], case['seed'] * 1000 + 900)
    probe = parse_probe(probe_raw, case, is_public)
    probe['expected_answer'] = case['source'] if is_public else 'unknown'
    probe['correct_public_grounding'] = probe['classification'] == probe['expected_answer']
    stated = case['alternative'] if 'false' in arm else case['source']
    probe['adopts_hint_location'] = probe['classification'] == stated if hint else None
    probe['raw_answer'] = probe_raw
    steps = []
    terminal = False
    for turn in range(args.max_steps):
        before = public_state(state)
        prompt = messages_for(case, observations, actions, state.admissible_commands)
        raw, finish = request_policy(args, [
            {'role':'system', 'content':with_hint(ACTION_SYSTEM, hint)},
            {'role':'user', 'content':prompt}], case['seed'] * 1000 + turn)
        command = raw.splitlines()[0].strip() if raw else ''
        evidence = pickup_evidence(command, known, state.admissible_commands)
        was_refuted = case['alternative'] in known and not any(
            obj.startswith('mug ') for obj in known[case['alternative']])
        after, reward, terminal = env.step(command)
        current = update_evidence(known, command, after.feedback, current)
        steps.append({
            'turn':turn, 'prompt_sha256':sha(prompt), 'action':command, 'raw_output':raw,
            'finish_reason':finish, 'before':before, 'observation':after.feedback,
            'admissible':command in before['admissible_commands'], 'pickup_evidence':evidence,
            'false_location_already_refuted':was_refuted,
            'navigates_to_false_after_refutation':was_refuted and command == f"go to {case['alternative']}",
            'reward':float(reward), 'terminal':bool(terminal), 'won':bool(after.won),
        })
        actions.append(command)
        observations.append(after.feedback)
        state = after
        if terminal:
            break
    env.close()
    nav = next((s['action'][6:] for s in steps if s['action'].startswith('go to ')), None)
    pickups = [s for s in steps if s['pickup_evidence'] and s['pickup_evidence']['object'].startswith('mug ')]
    result = {
        'case_id':case['case_id'], 'seed':case['seed'], 'arm':arm,
        'hint':hint, 'hint_sha256':sha(hint), 'starting_public_sha256':starting_hash,
        'is_public_fact_control':is_public, 'source':case['source'], 'alternative':case['alternative'],
        'grounding_probe':probe, 'steps':steps,
        'metrics': {
            'turns':len(steps), 'first_navigation_target':nav,
            'first_navigation_to_true':nav == case['source'],
            'first_navigation_to_false':nav == case['alternative'],
            'mug_pickup_attempts':len(pickups),
            'unverified_mug_pickup_attempts':sum(s['pickup_evidence']['unverified'] for s in pickups),
            'contradicted_mug_pickup_attempts':sum(s['pickup_evidence']['contradicted_by_observation'] for s in pickups),
            'invalid_actions':sum(not s['admissible'] for s in steps),
            'false_location_inspected':case['alternative'] in known,
            'returns_to_false_after_refutation':sum(s['navigates_to_false_after_refutation'] for s in steps),
            'won_within_horizon':any(s['won'] for s in steps),
        },
    }
    filename = case['case_id'].replace(':', '__') + f"__{arm}.json"
    write_json(args.output_dir / 'branches' / filename, result)
    print(f"done {case['case_id']} {arm}: nav={nav}, unverified={result['metrics']['unverified_mug_pickup_attempts']}, probe={probe_raw}", flush=True)
    return result


def mean(values):
    return sum(values) / len(values) if values else None


def summarize(branches, cases, args):
    by_arm = {}
    for arm in ARMS:
        selected = [r for r in branches if r['arm'] == arm]
        probe_valid = [r for r in selected if r['grounding_probe']['valid_output']]
        pickups = sum(r['metrics']['mug_pickup_attempts'] for r in selected)
        unsupported = sum(r['metrics']['unverified_mug_pickup_attempts'] for r in selected)
        by_arm[arm] = {
            'branches':len(selected),
            'first_navigation_to_true_rate':mean([r['metrics']['first_navigation_to_true'] for r in selected]),
            'first_navigation_to_false_rate':mean([r['metrics']['first_navigation_to_false'] for r in selected]),
            'grounding_probe_valid':len(probe_valid),
            'elicited_unsupported_assertion_rate':mean([r['grounding_probe']['unsupported_assertion'] for r in probe_valid]),
            'probe_correct_public_grounding_rate':mean([r['grounding_probe']['correct_public_grounding'] for r in selected]),
            'mug_pickup_attempts':pickups, 'unverified_mug_pickup_attempts':unsupported,
            'unverified_pickup_rate_given_attempt':unsupported/pickups if pickups else None,
            'contradicted_pickup_attempts':sum(r['metrics']['contradicted_mug_pickup_attempts'] for r in selected),
            'returns_to_false_after_refutation':sum(r['metrics']['returns_to_false_after_refutation'] for r in selected),
            'won_within_horizon_rate':mean([r['metrics']['won_within_horizon'] for r in selected]),
        }
    paired = []
    for case in cases:
        selected = {r['arm']:r for r in branches if r['case_id'] == case['case_id']}
        if set(selected) != set(ARMS):
            raise ValueError('missing paired arms')
        hidden = [r['starting_public_sha256'] for r in selected.values() if not r['is_public_fact_control']]
        public = [r['starting_public_sha256'] for r in selected.values() if r['is_public_fact_control']]
        if len(set(hidden)) != 1 or len(set(public)) != 1:
            raise ValueError('matched starting states differ')
        paired.append({
            'case_id':case['case_id'],
            'directional_navigation_flip':selected['true_fact']['metrics']['first_navigation_to_true']
                and selected['false_fact']['metrics']['first_navigation_to_false'],
            'paraphrase_same_first_navigation':selected['true_fact']['metrics']['first_navigation_target']
                == selected['paraphrase_true']['metrics']['first_navigation_target'],
            'true_probe':selected['true_fact']['grounding_probe'],
            'false_probe':selected['false_fact']['grounding_probe'],
        })
    return {
        'experiment':'same public state; hidden location substituted in otherwise identical hint',
        'model':args.model, 'temperature':args.temperature, 'seeds':args.seeds,
        'seed_application':'textworld.env.seed and per-step OpenAI-compatible sampling seed',
        'max_steps_per_branch':args.max_steps, 'case_count':len(cases), 'branches':len(branches),
        'hints':'controlled templates; no new GLM calls; true/false pair differs only in location string',
        'query':'full branch history plus current admissible commands',
        'evidence_rule':'navigation can reveal contents; observable object or exact public admissible take command grounds pickup',
        'elicited_probe':'separate grounding question, not a spontaneously generated assertion in an agent rollout',
        'arms':by_arm, 'paired':paired,
        'limitations':['3 scenes in one task family; 2 sampling seeds are correlated repeats, not 6 independent tasks',
                       'counterfactual hint is false in the unchanged environment, but physically plausible and compatible with initial public observations',
                       'short-horizon success is not full-task pass@k',
                       'controlled factual templates differ from prior full GLM L3 prose',
                       'admissible commands themselves provide public evidence and may suppress unsupported actions'],
    }


def self_test():
    h = build_hint('true_fact', 'cabinet 2', 'cabinet 3')
    assert h.replace('cabinet 2', 'cabinet 3') == build_hint('false_fact', 'cabinet 2', 'cabinet 3')
    known = {}
    update_evidence(known, 'go to countertop 1', 'You arrive at countertop 1. On it, you see a mug 1.', None)
    update_evidence(known, 'examine mug 1', 'This is a mug. In it, you see nothing.', 'countertop 1')
    assert 'mug 1' in known['countertop 1']
    assert not pickup_evidence('take mug 1 from countertop 1', known, [])['unverified']
    assert pickup_evidence('take mug 2 from countertop 1', known, [])['unverified']
    assert not pickup_evidence('take mug 2 from countertop 1', {}, ['take mug 2 from countertop 1'])['unverified']
    case = {'source':'countertop 1', 'alternative':'cabinet 2'}
    assert parse_probe('cabinet 2', case, False)['unsupported_assertion']
    assert not parse_probe('countertop 1', case, True)['unsupported_assertion']
    assert not parse_probe('unknown', case, False)['unsupported_assertion']
    print('PASS: factual intervention and observation/menu grounding controls', flush=True)


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--sessions', type=Path)
    p.add_argument('--output-dir', type=Path)
    p.add_argument('--policy-url', default='http://127.0.0.1:8000')
    p.add_argument('--model', default='Qwen3-4B')
    p.add_argument('--seeds', nargs='+', type=int, default=[42,43])
    p.add_argument('--max-steps', type=int, default=12)
    p.add_argument('--temperature', type=float, default=0.7)
    p.add_argument('--prepare-only', action='store_true')
    p.add_argument('--self-test', action='store_true')
    args = p.parse_args()
    self_test()
    if args.self_test:
        return
    if not args.sessions or not args.output_dir:
        p.error('--sessions and --output-dir required')
    if args.output_dir.exists() and any(args.output_dir.iterdir()):
        p.error('output directory must be empty')
    sessions = [json.loads(line) for line in args.sessions.read_text().splitlines() if line.strip()]
    cases = [prepare_case(s, seed) for s in sessions for seed in args.seeds]
    write_json(args.output_dir / 'cases.json', cases)
    print(json.dumps([{'case':c['case_id'], 'true':c['source'], 'false':c['alternative']} for c in cases]), flush=True)
    if args.prepare_only:
        return
    branches = []
    # Every branch owns a separate simulator instance and policy sampling seed.
    with ProcessPoolExecutor(max_workers=4, mp_context=multiprocessing.get_context('spawn')) as executor:
        futures = [executor.submit(run_branch, case, arm, args) for case in cases for arm in ARMS]
        for future in as_completed(futures):
            branches.append(future.result())
    branches.sort(key=lambda r:(r['case_id'], r['arm']))
    summary = summarize(branches, cases, args)
    write_json(args.output_dir / 'summary.json', summary)
    print(json.dumps(summary, ensure_ascii=False, indent=2), flush=True)


if __name__ == '__main__':
    main()
